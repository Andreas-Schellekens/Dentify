using Dentify.Contracts.Models;

namespace Dentify.Api.Strategies
{
    // Development stand-in for Azure OpenAI: builds the summary from a template
    public class FakeReportService : IReportService
    {
        public Task<string> WriteSummaryAsync(InspectionDetailDto inspection, InspectionDetailDto? previousInspection)
        {
            var damageCount = inspection.Damages.Count;

            var summary = damageCount == 0
                ? $"{inspection.Type} inspection of {inspection.VehicleLicensePlate}: no visible damage detected."
                : $"{inspection.Type} inspection of {inspection.VehicleLicensePlate}: {damageCount} damage(s) detected ("
                  + string.Join(", ", inspection.Damages.Select(d => $"{d.Severity.ToLower()} {d.Description.ToLower()} at {d.Location.ToLower()}"))
                  + ").";

            if (previousInspection != null)
            {
                var difference = damageCount - previousInspection.Damages.Count;
                summary += difference > 0
                    ? $" That is {difference} more than at the {previousInspection.Type.ToLower()} inspection of {previousInspection.Date:dd/MM/yyyy}."
                    : $" No new damage compared to the {previousInspection.Type.ToLower()} inspection of {previousInspection.Date:dd/MM/yyyy}.";
            }

            return Task.FromResult(summary + " (generated by the fake report service)");
        }
    }
}
